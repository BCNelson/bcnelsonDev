import { describe, expect, it, vi } from 'vitest';
import type { Env } from '../../src/env';
import { newClientSecret, validateClientFields, validateClientId, validateRedirectUri, verifyClientSecret } from '../../src/oidc/clients';
import { makeFakeEnv } from './fake-env';

vi.mock('cloudflare:workers', async () => ({
  DurableObject: (await import('./fake-storage')).FakeDurableObject,
}));

const { User } = await import('../../src/do/user');
const { UserIndex } = await import('../../src/do/user-index');

const env = { COOKIE_DOMAIN: 'bcnelson.dev', ISSUER: 'https://auth.bcnelson.dev' } as Env;

describe('client validation', () => {
  it('client ids: generated by default, reserved and site names refused for third parties', () => {
    const generated = validateClientId(undefined, false, env);
    expect(generated.ok && generated.value).toMatch(/^cli_[0-9a-z]{26}$/);
    expect(validateClientId('partner-app', false, env)).toEqual({ ok: true, value: 'partner-app' });
    for (const id of ['bcnelson.dev', 'auth.bcnelson.dev', 'bcnelson-sso', 'x.bcnelson.dev']) {
      expect(validateClientId(id, false, env).ok, id).toBe(false);
    }
    expect(validateClientId('bcnelson.dev', true, env).ok).toBe(false);
    expect(validateClientId('bcnelson-blog', true, env).ok).toBe(true);
    expect(validateClientId('UPPER', false, env).ok).toBe(false);
    expect(validateClientId('a', false, env).ok).toBe(false);
  });

  it('redirect URIs: canonical https, loopback http, never the auth host, site only for first party', () => {
    const ok = (u: string, fp = false) => validateRedirectUri(u, fp, env).ok;
    expect(ok('https://app.example.com/cb')).toBe(true);
    expect(ok('https://app.example.com/cb?x=1')).toBe(true);
    expect(ok('http://127.0.0.1:8080/cb')).toBe(true);
    expect(ok('http://localhost:3000/cb')).toBe(true);
    expect(ok('http://app.example.com/cb')).toBe(false);
    expect(ok('https://app.example.com')).toBe(false); // canonical form has a trailing slash
    expect(ok('https://user:pw@app.example.com/cb')).toBe(false);
    expect(ok('https://app.example.com/cb#frag')).toBe(false);
    expect(ok('javascript:alert(1)')).toBe(false);
    expect(ok('https://blog.bcnelson.dev/cb')).toBe(false);
    expect(ok('https://blog.bcnelson.dev/cb', true)).toBe(true);
    expect(ok('https://auth.bcnelson.dev/cb', true)).toBe(false);
  });

  it('fields: scopes must include openid; names may not borrow the site name', () => {
    const base = { name: 'Partner', redirect_uris: ['https://app.example.com/cb'] };
    const v = validateClientFields({ ...base, allowed_scopes: ['email', 'openid'] }, env);
    expect(v).toEqual({
      ok: true,
      value: {
        name: 'Partner', redirectUris: ['https://app.example.com/cb'], postLogoutRedirectUris: [],
        allowedScopes: ['openid', 'email'], firstParty: false,
      },
    });
    expect(validateClientFields({ ...base, allowed_scopes: ['email'] }, env)).toMatchObject({ ok: false, error: 'invalid_scope' });
    expect(validateClientFields({ ...base, name: 'BCNelson Login' }, env)).toMatchObject({ ok: false, error: 'invalid_name' });
    expect(validateClientFields({ ...base, name: 'BCNelson Login', first_party: true }, env).ok).toBe(true);
    expect(validateClientFields({ ...base, first_party: 'maybe' }, env).ok).toBe(false);
  });

  it('secrets verify in constant time against the stored hash only', async () => {
    const { secret, hash } = await newClientSecret();
    const record = { secretHash: hash } as Parameters<typeof verifyClientSecret>[0];
    expect(await verifyClientSecret(record, secret)).toBe(true);
    expect(await verifyClientSecret(record, `${secret.slice(0, -1)}A`)).toBe(secret.endsWith('A'));
    expect(await verifyClientSecret({ ...record, secretHash: null }, secret)).toBe(false);
  });
});

describe('UserIndex client registry', () => {
  it('creates, updates, rotates and disables; ids are unique', async () => {
    const fake = makeFakeEnv({ User, UserIndex });
    const index = fake.env.USER_INDEX.get(fake.env.USER_INDEX.idFromName('index'));
    const fields = {
      name: 'Partner', redirectUris: ['https://app.example.com/cb'], postLogoutRedirectUris: [],
      allowedScopes: ['openid'], firstParty: false,
    };
    const created = await index.createOAuthClient({ ...fields, clientId: 'partner', confidential: true, secretHash: 'h1' });
    expect(created).toMatchObject({ ok: true, client: { clientId: 'partner', secretHash: 'h1', confidential: true, disabledAt: null } });
    expect(await index.createOAuthClient({ ...fields, clientId: 'partner', confidential: false, secretHash: null }))
      .toEqual({ ok: false, reason: 'exists' });
    await expect(index.createOAuthClient({ ...fields, clientId: 'x2', confidential: true, secretHash: null })).rejects.toThrow();

    expect(await index.updateOAuthClient('partner', { ...fields, name: 'Renamed' })).toMatchObject({ ok: true, client: { name: 'Renamed' } });
    expect(await index.updateOAuthClient('missing', fields)).toEqual({ ok: false, reason: 'not_found' });
    expect(await index.setOAuthClientSecret('partner', 'h2')).toMatchObject({ ok: true, client: { secretHash: 'h2' } });

    await index.createOAuthClient({ ...fields, clientId: 'spa', confidential: false, secretHash: 'ignored' });
    expect((await index.getOAuthClient('spa'))!.secretHash).toBeNull();
    expect(await index.setOAuthClientSecret('spa', 'h')).toEqual({ ok: false, reason: 'not_found' });

    const disabled = await index.setOAuthClientDisabled('partner', true);
    expect(disabled.ok && disabled.client.disabledAt).toEqual(expect.any(Number));
    const enabled = await index.setOAuthClientDisabled('partner', false);
    expect(enabled.ok && enabled.client.disabledAt).toBeNull();
    expect((await index.listOAuthClients()).map((c: { clientId: string }) => c.clientId)).toEqual(['partner', 'spa']);
  });
});
